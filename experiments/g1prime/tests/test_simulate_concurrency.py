"""Unit tests for ``experiments/g1prime/simulate_concurrency.py``.

Uses the existing small-sample traces under ``physical_traces/`` (3 episodes
of ``airline-0`` with seeds 101112 / 123 / 131415). These traces were
generated by ``simulate_concurrency.py`` at c ∈ {1, 4, 8} and exercise the
concurrency simulator's behavioral contracts:

  1. ``c=1`` produces a strictly sequential workflow order (each workflow
     finishes before the next starts).
  2. ``c=4`` produces an interleaved workflow order (workflows overlap).
  3. ``access_idx`` is renumbered consecutively from 0 in every output trace.
  4. The total number of block accesses is preserved across concurrency levels
     (the simulator re-orders but does not drop or duplicate accesses).
"""

import json
from pathlib import Path

# conftest.py already puts g1prime/ on sys.path.
import simulate_concurrency as sc


G1PRIME_DIR: Path = Path(__file__).resolve().parent.parent
TRACE_DIR: Path = G1PRIME_DIR / "physical_traces"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _load_workflow_sequence(path: Path) -> list:
    """Read a per-concurrency access trace and return the workflow_id sequence."""
    wfs = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            wfs.append(rec.get("workflow_id", ""))
    return wfs


def _load_access_idx_sequence(path: Path) -> list:
    """Read a per-concurrency access trace and return the access_idx sequence."""
    idx = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            idx.append(rec["access_idx"])
    return idx


def _count_lines(path: Path) -> int:
    """Count non-empty lines in a jsonl file (one access per line)."""
    n = 0
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                n += 1
    return n


# ---------------------------------------------------------------------------
# 1. c=1: fully sequential
# ---------------------------------------------------------------------------
def test_c1_sequential():
    """c=1: workflow_id sequence is monotonic (each workflow completes before
    the next one starts; once a new workflow appears, prior ones never reappear).
    """
    path = TRACE_DIR / "access_trace_c1.jsonl"
    assert path.exists(), f"Missing trace: {path}"
    wfs = _load_workflow_sequence(path)
    assert len(wfs) > 0

    # Once a new workflow appears, none of the previously-seen workflows may
    # reappear later in the sequence.
    seen: set = set()
    seen.add(wfs[0])
    for i, w in enumerate(wfs[1:], start=1):
        if w not in seen:
            # New workflow starts — verify no previously-seen workflow reappears.
            for prev in seen:
                assert prev not in wfs[i:], (
                    f"c=1 not sequential: workflow {prev!r} reappeared after "
                    f"workflow {w!r} started at position {i}"
                )
            seen.add(w)


# ---------------------------------------------------------------------------
# 2. c=4: interleaved
# ---------------------------------------------------------------------------
def test_c4_interleaved():
    """c=4: workflow_id sequence is NOT monotonic (workflows interleave).

    Specifically, there must exist indices i < j < k such that
    ``wfs[i] == wfs[k] != wfs[j]`` (workflow at i reappears after a different
    workflow has appeared in between).
    """
    path = TRACE_DIR / "access_trace_c4.jsonl"
    assert path.exists(), f"Missing trace: {path}"
    wfs = _load_workflow_sequence(path)
    assert len(wfs) > 0

    # Detect interleaving: find i, j, k with wfs[i] == wfs[k] != wfs[j].
    interleaved = False
    for i in range(len(wfs)):
        for j in range(i + 1, len(wfs)):
            if wfs[j] == wfs[i]:
                break  # contiguous same workflow — keep scanning i
            if wfs[j] != wfs[i]:
                # Different workflow at j; check if wfs[i] reappears later at k.
                for k in range(j + 1, len(wfs)):
                    if wfs[k] == wfs[i]:
                        interleaved = True
                        break
                if interleaved:
                    break
        if interleaved:
            break

    assert interleaved, (
        "c=4 trace should be interleaved (workflow_id should reappear after "
        "an intervening different workflow_id)"
    )


# ---------------------------------------------------------------------------
# 3. access_idx renumbered from 0
# ---------------------------------------------------------------------------
def test_access_idx_renumbered():
    """access_idx is renumbered consecutively from 0 in every output trace."""
    for c in (1, 4, 8):
        path = TRACE_DIR / f"access_trace_c{c}.jsonl"
        assert path.exists(), f"Missing trace: {path}"
        idx = _load_access_idx_sequence(path)
        expected = list(range(len(idx)))
        assert idx == expected, (
            f"c={c}: access_idx not consecutive from 0 (len={len(idx)}; "
            f"first 5 actual={idx[:5]}, expected={expected[:5]})"
        )


# ---------------------------------------------------------------------------
# 4. Total accesses preserved across concurrency levels
# ---------------------------------------------------------------------------
def test_total_accesses_preserved():
    """All concurrency levels replay the same total block accesses.

    The simulator re-orders accesses but does NOT drop or duplicate any.
    For the small-sample trace this count is 17,258 (3 episodes × ~5,750
    block accesses each, modulo prefix overlap).
    """
    counts = {}
    for c in (1, 4, 8):
        path = TRACE_DIR / f"access_trace_c{c}.jsonl"
        assert path.exists(), f"Missing trace: {path}"
        counts[c] = _count_lines(path)

    values = list(counts.values())
    assert len(set(values)) == 1, (
        f"Access counts differ across concurrency levels: {counts}"
    )
    # Sanity check against the known small-sample size.
    assert values[0] == 17_258, (
        f"Expected 17,258 accesses on the small-sample trace, got {values[0]}"
    )


# ---------------------------------------------------------------------------
# 5. (Regression) Module-level path constants exist
# ---------------------------------------------------------------------------
def test_module_path_constants():
    """``simulate_concurrency.DEFAULT_INPUT_PATH`` points at access_trace.jsonl."""
    assert sc.DEFAULT_INPUT_PATH.name == "access_trace.jsonl"
    assert sc.DEFAULT_INPUT_PATH.parent == sc.DEFAULT_OUTPUT_DIR
